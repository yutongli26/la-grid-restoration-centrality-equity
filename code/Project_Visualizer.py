def ensure_dir(directory: str) -> bool:
    """Return True if directory exists; otherwise warn and return False."""
    if not os.path.exists(directory):
        print(f"  [Warning] Directory not found: {directory}")
        return False
    return True

def save_plot(fig: plt.Figure, folder: str, filename: str) -> None:
    """Save and close a matplotlib figure."""
    path = os.path.join(folder, filename)
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)
    print(f"  [Saved] {filename}")

def load_shapefile():
    """
    Load the tract shapefile and standardize the tract id column name to 'tract_id'.
    Returns:
        GeoDataFrame or None
    """
    if not os.path.exists(SHAPEFILE_PATH):
        print(f"  [GIS Skip] Shapefile not found at {SHAPEFILE_PATH}")
        return None

    try:
        gdf = gpd.read_file(SHAPEFILE_PATH)

        possible_cols = ["GEOID", "GEOID10", "GEOID20", "TRACTCE", "TRACT", "geoid"]
        for c in possible_cols:
            if c in gdf.columns:
                gdf["tract_id"] = gdf[c].astype(str).str.strip()
                break

        if "tract_id" not in gdf.columns:
            print("  [GIS Warning] Could not identify Tract ID column in shapefile.")
            return None

        return gdf

    except Exception as e:
        print(f"  [GIS Error] Failed to load shapefile: {e}")
        return None

def plot_map(
    gdf,
    data_series,
    title: str,
    output_dir: str,
    filename: str,
    cmap: str = "OrRd",
    label: str = "Value",
    vmin=None,
    vmax=None,
    cmap_low: float = 0.1,
    cmap_high: float = 1.0,
):
    """
    Enhanced mapping utility:
      1) Robust tract-id matching with multiple strategies.
      2) Optional shared vmin/vmax (if provided).
      3) Truncated colormap (cuts off very light colors).
      4) Larger title/label/ticks for publication-ready maps.
    """
    if gdf is None:
        return

    # ---- Prepare data ----
    data_df = data_series.to_frame(name="val")
    data_df.index = (
        data_df.index.astype(str)
        .str.split(".").str[0]
        .str.strip()
    )

    gdf["tract_id"] = (
        gdf["tract_id"].astype(str)
        .str.split(".").str[0]
        .str.strip()
    )

    print(f"\n[GIS Debug] Trying to map: {title}")

    # ---- Matching strategies ----
    matched_gdf = None
    best_match_count = 0

    strategies = [
        ("Direct", lambda s: s),
        ("CSV zfill 11", lambda s: s.str.zfill(11)),
        ("Shapefile zfill 11", None),
        ("Suffix 6", lambda s: s.str[-6:]),
    ]

    for name, func in strategies:
        temp_data = data_df.copy()
        temp_gdf = gdf.copy()

        if name == "Shapefile zfill 11":
            temp_gdf["tract_id"] = temp_gdf["tract_id"].str.zfill(11)
        elif func:
            temp_data.index = func(temp_data.index)

        merged = temp_gdf.merge(
            temp_data,
            left_on="tract_id",
            right_index=True,
            how="inner",
        )

        count = len(merged)
        if count > best_match_count:
            best_match_count = count
            matched_gdf = merged
            print(f"   > Strategy '{name}' matched: {count} tracts")

    if best_match_count == 0 or matched_gdf is None:
        print("   ❌ [GIS Error] ALL MATCHING STRATEGIES FAILED.")
        return

    print(f"   ✅ Final Map Area: {best_match_count} tracts.")

    # ---- Plot ----
    fig, ax = plt.subplots(figsize=(10, 10))

    # vmin/vmax based on finite values only
    data_vals = matched_gdf["val"].astype(float)
    data_vals_valid = data_vals[np.isfinite(data_vals)]
    if vmin is None:
        vmin = float(data_vals_valid.min())
    if vmax is None:
        vmax = float(data_vals_valid.max())

    # Truncated colormap to avoid near-white low end
    base_cmap = plt.colormaps.get_cmap(cmap)
    new_colors = base_cmap(np.linspace(cmap_low, cmap_high, 256))
    truncated_cmap = mcolors.LinearSegmentedColormap.from_list(
        f"{cmap}_trunc_{cmap_low}_{cmap_high}",
        new_colors,
    )

    matched_gdf.plot(
        column="val",
        ax=ax,
        legend=False,
        cmap=truncated_cmap,
        vmin=vmin,
        vmax=vmax,
        missing_kwds={
            "color": "lightgrey",
            "edgecolor": "none",
            "hatch": "///",
        },
    )

    # Colorbar
    divider = make_axes_locatable(ax)
    cax = divider.append_axes("right", size="5%", pad=0.1)

    sm = plt.cm.ScalarMappable(
        cmap=truncated_cmap,
        norm=plt.Normalize(vmin=vmin, vmax=vmax),
    )
    sm._A = []  # dummy for ScalarMappable

    ticks = np.linspace(vmin, vmax, 5)
    cbar = fig.colorbar(sm, cax=cax, ticks=ticks)
    cbar.ax.set_yticklabels([f"{t:.2f}" for t in ticks], fontsize=25)
    cbar.set_label(label, fontsize=25)

    ax.set_title(title, fontsize=25, fontweight="bold", pad=12)
    ax.axis("off")

    # Save
    if "save_plot" in globals():
        save_plot(fig, output_dir, filename)
    else:
        import os  # kept to preserve the original structure/behavior

        os.makedirs(output_dir, exist_ok=True)
        plt.savefig(os.path.join(output_dir, filename), bbox_inches="tight")

    plt.close(fig)

def vis_stage1(gdf):
    """
    Stage 1 visualization (TRACT SUPPLY + SUBSTATION AVG DS).

    Inputs expected in:  <OUTPUT_ROOT>/Stage 1 Output/
      - MC_Tract_Supply_<SCEN>.csv         columns: tract_id, scenario, supply
      - MC_Device_Damage_AvgDS_<SCEN>.csv  columns: substation_id, scenario, avg_damage_state

    Outputs:
      - map_supply_<SCEN>.png
      - hist_supply_<SCEN>.png
      - hist_sub_avg_ds_<SCEN>.png
    """
    stage_dir = os.path.join(OUTPUT_ROOT, "Stage 1 Output")
    if not ensure_dir(stage_dir):
        return

    print("--- Visualizing Stage 1 ---")

    # -------------------------------------------------------------------------
    # Global plotting style (big fonts, readable)
    # -------------------------------------------------------------------------
    try:
        sns.set_style("whitegrid")
        sns.set_context("talk", font_scale=1.2)
    except Exception:
        plt.style.use("ggplot")

    # -------------------------------------------------------------------------
    # 1) Global color normalization for SUPPLY maps (consistent across scenarios)
    #    Use robust bounds (p1–p99) to avoid "all one color" when values cluster.
    # -------------------------------------------------------------------------
    all_supply_vals = []
    for scen in SCENARIOS:
        supply_file = os.path.join(stage_dir, f"MC_Tract_Supply_{scen}.csv")
        if not os.path.exists(supply_file):
            continue

        df_tmp = pd.read_csv(supply_file)
        if "supply" not in df_tmp.columns:
            continue

        s = pd.to_numeric(df_tmp["supply"], errors="coerce").clip(0.0, 1.0)
        s = s[np.isfinite(s)]
        if len(s) > 0:
            all_supply_vals.append(s.values)

    if all_supply_vals:
        vals = np.concatenate(all_supply_vals)
        vals = vals[np.isfinite(vals)]
        if vals.size > 0:
            supply_vmin = float(np.nanquantile(vals, 0.01))
            supply_vmax = float(np.nanquantile(vals, 0.99))
            supply_vmin = max(0.0, min(1.0, supply_vmin))
            supply_vmax = max(0.0, min(1.0, supply_vmax))
            if supply_vmax - supply_vmin < 1e-6:
                supply_vmin, supply_vmax = 0.0, 1.0
        else:
            supply_vmin, supply_vmax = 0.0, 1.0
    else:
        supply_vmin, supply_vmax = 0.0, 1.0

    # -------------------------------------------------------------------------
    # 2) Per-scenario plots
    # -------------------------------------------------------------------------
    for scen in SCENARIOS:
        # ===================== Tract Mean Supply Map ==========================
        supply_file = os.path.join(stage_dir, f"MC_Tract_Supply_{scen}.csv")
        if os.path.exists(supply_file):
            df = pd.read_csv(supply_file)

            if ("tract_id" in df.columns) and ("supply" in df.columns):
                # Normalize tract_id to match GIS layer keys
                df["tract_id"] = df["tract_id"].astype(str).str.split(".").str[0]

                # Mean supply in [0,1]
                supply = pd.to_numeric(
                    df.set_index("tract_id")["supply"],
                    errors="coerce",
                ).clip(0.0, 1.0)

                # Map: red -> blue
                plot_map(
                    gdf=gdf,
                    data_series=supply,
                    title=f"Mean Supply - {scen}",
                    output_dir=stage_dir,
                    filename=f"map_supply_{scen}.png",
                    cmap="RdBu",
                    label="Mean Supply (0–1)",
                    vmin=0.0,     
                    vmax=1.0,     
                    cmap_low=0.0,
                    cmap_high=1.0,
                )

                # Distribution: histogram + KDE
                fig, ax = plt.subplots(figsize=(8, 5))
                sns.histplot(
                    supply.dropna(),
                    bins=np.linspace(0, 1, 21),
                    stat="density",
                    kde=True,
                    color="#e41a1c",
                    edgecolor="black",
                    alpha=0.6,
                    ax=ax,
                )
                ax.set_title(
                    f"Distribution of Mean Supply - {scen}",
                    fontsize=20,
                    fontweight="bold",
                    pad=10,
                )
                ax.set_xlabel("Mean Supply (0–1)", fontsize=18)
                ax.set_ylabel("Density", fontsize=18)
                ax.set_xlim(0.0, 1.0)
                ax.tick_params(axis="both", labelsize=14)

                save_plot(fig, stage_dir, f"hist_supply_{scen}.png")
                plt.close(fig)
            else:
                print(f"  [Stage 1] Missing columns in {supply_file}; expected tract_id & supply.")

        # ===================== Substation Avg Damage State ====================
        dev_file = os.path.join(stage_dir, f"MC_Device_Damage_AvgDS_{scen}.csv")
        if os.path.exists(dev_file):
            df = pd.read_csv(dev_file)

            fig, ax = plt.subplots(figsize=(8, 5))
            sns.histplot(
                data=df,
                x="avg_damage_state",
                bins=np.linspace(0, 4, 17),  # 0–4 in 0.25 increments
                stat="density",
                color="orange",
                edgecolor="black",
                alpha=0.6,
                ax=ax,
            )
            sns.kdeplot(
                data=df,
                x="avg_damage_state",
                color="black",
                linewidth=2,
                ax=ax,
            )

            ax.set_title(
                f"Substation Average Damage State – {scen}",
                fontsize=20,
                fontweight="bold",
                pad=10,
            )
            ax.set_xlabel("Average damage state (0 = none, 4 = collapse)", fontsize=18)
            ax.set_ylabel("Density", fontsize=18)
            ax.set_xlim(0.0, 4.0)
            ax.tick_params(axis="both", labelsize=14)

            save_plot(fig, stage_dir, f"hist_sub_avg_ds_{scen}.png")
            plt.close(fig)

