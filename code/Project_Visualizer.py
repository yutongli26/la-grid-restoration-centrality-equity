def vis_stage7_cluster_top10_impact_degree_km(
    gdf,
    cluster_id: int = 0,
    top_n: int = 10,
    impact_mode: str = "lambda2",  # "lambda2" or "pop"
) -> None:
    """
    Stage 7: Visualize cluster map with top-N impact degree substations.
    """
    stage7_dir = os.path.join(OUTPUT_ROOT, "Stage 7 Output")
    if not ensure_dir(stage7_dir):
        return
    if gdf is None or gdf.empty:
        print("  [Stage 7] gdf is None/empty, skip cluster+top10 map.")
        return

    csv_path = os.path.join(stage7_dir, "clusters_labels_final.csv")
    if not os.path.exists(csv_path):
        print("  [Stage 7] clusters_labels_final.csv not found, skip cluster+top10 map.")
        return

    df_clu = pd.read_csv(csv_path)
    if df_clu.empty or ("tract_id" not in df_clu.columns) or ("cluster" not in df_clu.columns):
        print("  [Stage 7] clusters CSV missing tract_id/cluster, skip cluster+top10 map.")
        return

    def _norm_tract_id(s: pd.Series) -> pd.Series:
        return (
            s.astype(str)
             .str.extract(r"(\d+)")[0]
             .str.zfill(11)
        )

    df_clu = df_clu[["tract_id", "cluster"]].copy()
    df_clu["tract_id"] = _norm_tract_id(df_clu["tract_id"])
    df_clu["cluster"] = df_clu["cluster"].astype(str)
    clu_key = str(cluster_id)

    g_all = gdf.copy()
    if "tract_id" not in g_all.columns:
        print("  [Stage 7] gdf missing tract_id, skip cluster+top10 map.")
        return
    g_all["tract_id"] = _norm_tract_id(g_all["tract_id"])

    try:
        g_all = g_all.to_crs(epsg=3310)
    except Exception:
        pass

    # --- Load LA City boundary (for zoom + clip) ---
    city = None
    city_union = None
    if os.path.exists(CITY_BOUNDARY_SHP):
        try:
            city = gpd.read_file(CITY_BOUNDARY_SHP)
            if city.crs is None:
                minx, miny, maxx, maxy = city.total_bounds
                if -180 <= minx <= 180 and -90 <= miny <= 90:
                    city = city.set_crs(epsg=4326)
            city = city.to_crs(epsg=3310)
            city_union = city.geometry.union_all()
        except Exception:
            city = None
            city_union = None

    # --- Clip tracts to LA City (zoom-in fix) ---
    if city_union is not None:
        try:
            g_all = g_all[g_all.geometry.intersects(city_union)].copy()
        except Exception:
            pass

    # --- Compute LA center (use city centroid if available) ---
    if city_union is not None:
        c0 = city_union.centroid
        center_x, center_y = float(c0.x), float(c0.y)
    else:
        c0 = g_all.geometry.union_all().centroid
        center_x, center_y = float(c0.x), float(c0.y)

    from shapely.affinity import translate, scale

    def _km_shift(geom):
        if geom is None or geom.is_empty:
            return geom
        g0 = translate(geom, xoff=-center_x, yoff=-center_y)
        return scale(g0, xfact=1.0 / 1000.0, yfact=1.0 / 1000.0, origin=(0.0, 0.0))

    g_all_km = g_all.copy()
    g_all_km["geometry"] = g_all_km.geometry.apply(_km_shift)
    g_all_km = g_all_km.set_crs(None, allow_override=True)

    # --- Merge cluster labels (and clip again to city if needed) ---
    merged = g_all.merge(df_clu, on="tract_id", how="left")
    merged_km = merged.copy()
    merged_km["geometry"] = merged_km.geometry.apply(_km_shift)
    merged_km = merged_km.set_crs(None, allow_override=True)

    cluster_polys = merged_km.loc[merged_km["cluster"] == clu_key].copy()

    # --- City boundary in km coords ---
    city_km = None
    if city is not None and not city.empty:
        city_km = city.copy()
        city_km["geometry"] = city_km.geometry.apply(_km_shift)
        city_km = city_km.set_crs(None, allow_override=True)

    # --- Load all substations ---
    if not os.path.exists(DEVICES_CSV):
        print(f"  [Stage 7] Devices CSV not found: {DEVICES_CSV}")
        return
    devices = pd.read_csv(DEVICES_CSV)

    dev_id_col = "HIFLD_ID"
    if dev_id_col not in devices.columns:
        if "id" in devices.columns:
            dev_id_col = "id"
        elif "OBJECTID" in devices.columns:
            dev_id_col = "OBJECTID"

    lat_col = next((c for c in ["lat", "Latitude", "Lat", "latitude", "LATITUDE"] if c in devices.columns), None)
    lon_col = next((c for c in ["lon", "Longitude", "Lon", "longitude", "LONGITUDE"] if c in devices.columns), None)
    if lat_col is None or lon_col is None:
        print("  [Stage 7] lat/lon columns not found in devices, skip cluster+top10 map.")
        return

    all_subs = gpd.GeoDataFrame(
        devices,
        geometry=gpd.points_from_xy(devices[lon_col], devices[lat_col]),
        crs="EPSG:4326",
    )
    try:
        all_subs = all_subs.to_crs(epsg=3310)
    except Exception:
        pass

    # Clip substations to a buffered city bbox for cleaner view (optional but helps)
    if city_union is not None:
        try:
            all_subs = all_subs[all_subs.geometry.within(city_union.buffer(20000))].copy()  # 20 km buffer
        except Exception:
            pass

    all_subs_km = all_subs.copy()
    all_subs_km["geometry"] = all_subs_km.geometry.apply(_km_shift)
    all_subs_km = all_subs_km.set_crs(None, allow_override=True)

    # --- Load centrality and pick TopN by impact + degree ---
    stage2_dir = os.path.join(OUTPUT_ROOT, "Stage 2 Output")
    cent_file = os.path.join(stage2_dir, "impact_centrality_substations.csv")

    top_impact_km = None
    top_degree_km = None

    def _pick_col(frame: pd.DataFrame, prefer_list, contains_list):
        for p in prefer_list:
            if p in frame.columns:
                return p
        for c in frame.columns:
            cl = c.lower()
            for kw in contains_list:
                if kw in cl:
                    return c
        return None

    def _clean_id_series(s: pd.Series) -> pd.Series:
        return s.astype(str).str.strip().str.replace(".0", "", regex=False)

    if os.path.exists(cent_file):
        df_cent = pd.read_csv(cent_file)
        if not df_cent.empty:
            id_col = df_cent.columns[0]
            degree_col = _pick_col(df_cent, ["degree"], ["degree"])

            if impact_mode.lower() == "pop":
                impact_col = _pick_col(df_cent, ["impact_pop", "impact_population"], ["impact", "pop"])
            else:
                impact_col = _pick_col(df_cent, ["impact_lambda2", "impact_l2", "impact_eig"], ["lambda2", "l2", "eig"])
            if impact_col is None:
                impact_col = _pick_col(df_cent, ["impact", "Impact"], ["impact"])

            devices["join_key"] = _clean_id_series(devices[dev_id_col])
            df_cent["join_key"] = _clean_id_series(df_cent[id_col])

            if impact_col is not None:
                top_imp = df_cent.nlargest(int(top_n), impact_col).merge(devices, on="join_key", how="left")
                top_imp_gdf = gpd.GeoDataFrame(
                    top_imp,
                    geometry=gpd.points_from_xy(top_imp[lon_col], top_imp[lat_col]),
                    crs="EPSG:4326",
                )
                try:
                    top_imp_gdf = top_imp_gdf.to_crs(epsg=3310)
                except Exception:
                    pass
                if city_union is not None:
                    try:
                        top_imp_gdf = top_imp_gdf[top_imp_gdf.geometry.within(city_union.buffer(20000))].copy()
                    except Exception:
                        pass
                top_impact_km = top_imp_gdf.copy()
                top_impact_km["geometry"] = top_impact_km.geometry.apply(_km_shift)
                top_impact_km = top_impact_km.set_crs(None, allow_override=True)

            if degree_col is not None:
                top_deg = df_cent.nlargest(int(top_n), degree_col).merge(devices, on="join_key", how="left")
                top_deg_gdf = gpd.GeoDataFrame(
                    top_deg,
                    geometry=gpd.points_from_xy(top_deg[lon_col], top_deg[lat_col]),
                    crs="EPSG:4326",
                )
                try:
                    top_deg_gdf = top_deg_gdf.to_crs(epsg=3310)
                except Exception:
                    pass
                if city_union is not None:
                    try:
                        top_deg_gdf = top_deg_gdf[top_deg_gdf.geometry.within(city_union.buffer(20000))].copy()
                    except Exception:
                        pass
                top_degree_km = top_deg_gdf.copy()
                top_degree_km["geometry"] = top_degree_km.geometry.apply(_km_shift)
                top_degree_km = top_degree_km.set_crs(None, allow_override=True)
    else:
        print(f"  [Stage 7] Centrality file not found: {cent_file}")

    # --- Plot (zoomed) ---
    fig, ax = plt.subplots(figsize=(7.5, 7.5))

    g_all_km.boundary.plot(ax=ax, color="#d0d0d0", linewidth=0.5, zorder=0)

    if city_km is not None and not city_km.empty:
        city_km.boundary.plot(ax=ax, color="#4a4a4a", linewidth=1.6, zorder=1)

    if not cluster_polys.empty:
        cluster_polys.plot(ax=ax, color="#f4a582", edgecolor="none", alpha=0.75, zorder=2)

    all_subs_km.plot(
        ax=ax, marker="x", color="#6e6e6e",
        markersize=26, linewidth=1.1, alpha=0.75,
        label="All substations", zorder=3,
    )

    if top_impact_km is not None and not top_impact_km.empty:
        top_impact_km.plot(
            ax=ax, marker="o", color="#1f77b4",
            markersize=85, linewidth=0.0,
            label=f"Top {int(top_n)} by impact ({impact_mode})", zorder=4,
        )

    if top_degree_km is not None and not top_degree_km.empty:
        top_degree_km.plot(
            ax=ax, marker="^", color="#2ca02c",
            markersize=95, linewidth=0.0,
            label=f"Top {int(top_n)} by degree", zorder=5,
        )

    ax.set_title(f"Cluster {clu_key} Tracts (Shaded) with Top-{int(top_n)} Substations", fontsize=14, pad=10)
    ax.set_xlabel("East–West distance from LA center (km)", fontsize=12)
    ax.set_ylabel("North–South distance from LA center (km)", fontsize=12)
    ax.set_aspect("equal", "box")

    # Zoom to LA City bounds (fallback: tracts bounds)
    if city_km is not None and not city_km.empty:
        minx, miny, maxx, maxy = city_km.total_bounds
    else:
        minx, miny, maxx, maxy = g_all_km.total_bounds

    pad_x = (maxx - minx) * 0.06
    pad_y = (maxy - miny) * 0.06
    ax.set_xlim(minx - pad_x, maxx + pad_x)
    ax.set_ylim(miny - pad_y, maxy + pad_y)
    ax.tick_params(axis='both', which='major', labelsize=12)
    # Legend fix (smaller + inside + no overflow)
    ax.legend(
        loc="upper center",
        bbox_to_anchor=(0.5, -0.12),
        fontsize=11,
        frameon=True,
        framealpha=0.92,
        borderpad=0.6,
        labelspacing=0.4,
        handletextpad=0.6,
        handlelength=1.6,
        markerscale=0.9,
    )

    fig.tight_layout()
    save_plot(fig, stage7_dir, f"vis_stage7_cluster{clu_key}_top{int(top_n)}_impact_{impact_mode}_degree_km.png")

