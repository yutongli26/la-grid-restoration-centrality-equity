def vis_stage5():
    """
    Visualize Stage 5 GA results:
    Iterates through individual GA_Schedule_*.csv files to plot Gantt charts.
    """
    # 1. Locate output directory (Stage 5 Output or Stage5_Results)
    stage_dir = os.path.join(OUTPUT_ROOT, "Stage 5 Output")
    if not os.path.exists(stage_dir):
        stage_dir = os.path.join(OUTPUT_ROOT, "Stage5_Results")
        if not os.path.exists(stage_dir):
            print(f"[Warn] Stage 5 output directory not found.")
            return

    print(f"--- Visualizing Stage 5 (GA Optimization) in {stage_dir} ---")

    # 2. Find all schedule files matching the pattern
    search_pattern = os.path.join(stage_dir, "GA_Schedule_*.csv")
    found_files = glob.glob(search_pattern)
    
    if not found_files:
        print("  [Warn] No 'GA_Schedule_*.csv' files found.")
        return

    print(f"  [Info] Found {len(found_files)} schedule files. Processing...")

    # 3. Plot Gantt chart for each file
    for file_path in found_files:
        try:
            filename = os.path.basename(file_path)
            # Parse scenario name from filename (e.g., GA_Schedule_Northridge_Balanced.csv -> Northridge_Balanced)
            clean_name = filename.replace("GA_Schedule_", "").replace(".csv", "")
            
            df = pd.read_csv(file_path)
            if df.empty:
                continue
                
            # --- Data Preparation for Plotting ---
            
            # (A) Generate Crew_ID if missing (using Resource_Type + Index)
            if "Crew_ID" not in df.columns:
                if "Resource_Type" in df.columns:
                    df["Crew_ID"] = df["Resource_Type"] + "_" + df.index.astype(str)
                else:
                    df["Crew_ID"] = df.index

            # (B) Calculate Duration if missing
            if "Duration" not in df.columns:
                if "Finish_Time" in df.columns and "Start_Time" in df.columns:
                    df["Duration"] = df["Finish_Time"] - df["Start_Time"]
                else:
                    df["Duration"] = 1.0  # Fallback

            # (C) Default Travel_Time to 0 if missing
            if "Travel_Time" not in df.columns:
                df["Travel_Time"] = 0.0

            # (D) Skip if Start_Time is missing
            if "Start_Time" not in df.columns:
                print(f"    [Skip] {filename} missing 'Start_Time'.")
                continue

            # 4. Generate Plot
            plot_title = f"Stage5_GA_{clean_name}"
            plot_gantt_chart(df, stage_dir, plot_title)
            print(f"    -> Plotted: {filename}")

        except Exception as e:
            print(f"    [Error] Failed to plot {filename}: {e}")

    print("--- Stage 5 Visualization Complete ---")

